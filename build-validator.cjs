// Regenerate after changing tracker.schema.json. Uses existing backend dev dependencies.
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const { createRequire } = require("node:module");
const dependencies = createRequire(path.join(__dirname, "package.json"));
const Ajv = dependencies("ajv/dist/2020");
const formats = dependencies("ajv-formats");
const standalone = dependencies("ajv/dist/standalone").default;
const esbuild = dependencies("esbuild");
const schema = JSON.parse(
  fs.readFileSync(path.join(__dirname, "tracker.schema.json"), "utf8"),
);
const ajv = new Ajv({
  allErrors: true,
  strict: true,
  strictRequired: false,
  code: { source: true },
});
ajv.addKeyword({ keyword: "x-ui", valid: true });
formats(ajv);
ajv.addSchema(schema);
const compiled = standalone(ajv, {
  tracker: schema.$id,
  todo: schema.$id + "#/$defs/todoFile",
});
const digest = crypto
  .createHash("sha256")
  .update(JSON.stringify(schema))
  .digest("hex");
const helpers = `
exports.schemaHash = ${JSON.stringify(digest)};
exports.statuses = ${JSON.stringify(Object.keys(schema.$defs.status["x-ui"]))};
exports.statusUI = ${JSON.stringify(schema.$defs.status["x-ui"])};
exports.commentLimit = ${schema.$defs.row.properties.comments.maxLength};
exports.checkRows = function(rows,file) {
 const validator=file==='data/todo.json'?exports.todo:exports.tracker;
 const valid=validator(rows);
 const errors=valid?[]:validator.errors.map(e=>(e.instancePath||'/')+' '+e.message+(e.keyword==='enum'?': '+e.params.allowedValues.join(', '):e.keyword==='additionalProperties'?': '+e.params.additionalProperty:''));
 if(Array.isArray(rows)) {
  const ids=new Set();
  rows.forEach((row,i)=>{
   if(!row||typeof row!=='object'||Array.isArray(row))return;
   if(ids.has(row.id))errors.push('/'+i+'/id duplicate row ID: '+row.id);
   ids.add(row.id);
   if(/(?:^|\\/)bug\\.[^/]+\\.json$/.test(file)&&typeof row.bug!=='string')errors.push('/'+i+'/bug is required in a bug file');
   if(/(?:^|\\/)feature\\.[^/]+\\.json$/.test(file)&&typeof row.task!=='string')errors.push('/'+i+'/task is required in a feature file');
  });
 }
 return {valid:errors.length===0,errors};
};
`;
const built = esbuild.buildSync({
  stdin: {
    contents: compiled + helpers,
    resolveDir: __dirname,
  },
  bundle: true,
  platform: "browser",
  format: "iife",
  globalName: "ProgressTrackerSchema",
  write: false,
  minify: false,
  legalComments: "inline",
});
fs.writeFileSync(
  path.join(__dirname, "tracker-validator.js"),
  "// Generated by node progress/build-validator.cjs; edit tracker.schema.json instead.\n" +
    built.outputFiles[0].text +
    '\nif (typeof module !== "undefined" && module.exports) module.exports = ProgressTrackerSchema;\n',
);
console.log("Generated shared tracker validator:", digest);
